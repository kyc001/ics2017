// memory.c - 物理内存实现
// 功能：定义 NEMU 模拟的物理内存（128MB 的字节数组）
// 这个数组就是"客户机（被模拟的 x86 程序）"看到的全部物理内存

#include "nemu.h"     // NEMU 全局定义

// pmem = Physical Memory（物理内存）
// 这是一个 128MB 的字节数组，代表被模拟计算机的全部物理内存
// PMEM_SIZE 在 memory.h 中定义为 128 * 1024 * 1024（128MB）
uint8_t pmem[PMEM_SIZE];

// ──────────────────────────────────────────────────────────────────────────────
// 内存模拟的原理：
//
// NEMU 用一个大数组 pmem[] 来模拟物理内存：
//   - 客户机（被模拟的 x86 程序）认为自己有 128MB 物理内存（地址 0x00000000 - 0x07FFFFFF）
//   - 实际上这些内存存在 NEMU 进程的 pmem[] 数组里
//   - 当客户机访问地址 0x100000 时，NEMU 实际访问 pmem[0x100000]
//
// 地址转换关系：
//   客户机物理地址（paddr）→ NEMU 宿主机虚拟地址（host virtual address）
//   例如：客户机地址 0x100000 → NEMU 的 &pmem[0x100000]
//
// 这就是"模拟器"的本质：用软件（数组）假装成硬件（内存芯片）
// ──────────────────────────────────────────────────────────────────────────────
